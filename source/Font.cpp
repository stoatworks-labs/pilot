const char* const* Glyph( int code )
{
	if( code < kFirst || code >= kFirst + kCount )
		return kBlank;
	return kGlyphs[ code - kFirst ];
}

bool Bit( int code, int x, int y )
{
	if( x < 0 || x >= kWidth || y < 0 || y >= kHeight )
		return false;
	return Glyph( code )[ y ][ x ] == '#';
}

std::vector< uint8_t > Texture()
{
	std::vector< uint8_t > out( static_cast< size_t >( kTextureWidth ) * kTextureHeight, 0 );
	for( int code = 0; code < 128; ++code )
		for( int y = 0; y < kHeight; ++y )
			for( int x = 0; x < kWidth; ++x )
				if( Bit( code, x, y ) )
					out[ static_cast< size_t >( y ) * kTextureWidth + code * kWidth + x ] = 255;
	return out;
}

